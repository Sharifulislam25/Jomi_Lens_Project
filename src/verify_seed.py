def _survey_rows(sc):
    """CS -> SA -> RS -> BS survey references. Dag numbers change between surveys, each later one declares the earlier dag (prev_dag_ref)."""
    if sc.get("surveys") is None and "surveys" in sc:
        return []
    base = int(re.sub(r"\D", "", sc.get("dag") or "125") or 125)
    d0, d1, d2, d3 = base - 27, base - 13, base, base
    a = sc["area_dec"]
    areas = [a * 1.06, a * 1.05, a * 1.04, a]
    prevs = [None, d0, d1, d2]
    if sc.get("surveys") == "drift":
        areas[2] = 12.0
    if sc.get("surveys") == "lineage":
        prevs[3] = 140
    kh = sc.get("khatian") or (sc["core"][1]["kh"] if len(sc["core"]) > 1 else (sc["core"][0]["kh"] if sc["core"] else "KH-0"))
    out = []
    for gen, year, dag, prev, area in zip(["CS", "SA", "RS", "BS"], [1962, 1976, 1991, 2015], [d0, d1, d2, d3], prevs, areas):
        out.append(dict(t="survey reference", ref=f"DEMO-{gen}-{sc['pid'][-3:]}", dag=str(dag), kh=kh, a=round(area, 2), u="decimal", d=f"{year}-01-01", p=None,
                        off="Survey Office (synthetic)", gen=gen, prev=str(prev) if prev else None))
    return out


def doc_bytes(rec, parcel_id, altered=False) -> bytes:
    area = f"{rec['a'] + 1.0:.2f} (CHANGED)" if altered else rec["a"]
    return (f"SYNTHETIC DEMO DOCUMENT - NOT A REAL LAND RECORD\nType: {rec['t']}\nReference: {rec['ref']}\nParcel (internal ID): {parcel_id}\nDag: {rec['dag']}\n"
            f"Khatian: {rec['kh']}\nRecorded area: {area} {rec['u']}\nDate: {rec['d']}\nParty label: {rec['p']}\n").encode()


def rect_points(lon, lat, area_sqm):
    w = math.sqrt(area_sqm * 1.4)
    h = area_sqm / w
    n, s = GEOD.fwd(lon, lat, 0, h / 2)[1], GEOD.fwd(lon, lat, 180, h / 2)[1]
    e, wst = GEOD.fwd(lon, lat, 90, w / 2)[0], GEOD.fwd(lon, lat, 270, w / 2)[0]
    return [(wst, n), (e, n), (e, s), (wst, s)]


def grid_point(index: int):
    """Fixed demo positions over the Joydebpur focus area: 5 fictional mouzas (rows) x 5 parcels (same grid as the MERN version)."""
    row, col = divmod(index, 5)
    return round(90.4075 + col * 0.0085, 5), round(24.0145 - row * 0.0075, 5)


def mouza_of(index: int) -> int:
    return index // 5 + 1


def asking_price_bdt(index: int, area_decimal: float) -> int:
    """Fictional asking price: mouza rate x area, with a small fixed variation per parcel, rounded to 10,000 BDT."""
    rate = PRICE_LAKH_PER_DECIMAL[mouza_of(index)] * 100_000 * (0.92 + 0.04 * (index % 5))
    return int(round(rate * area_decimal / 10_000) * 10_000)


