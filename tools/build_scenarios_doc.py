"""Regenerate docs/DEMO_SCENARIOS.md from the engine (so the table can never drift from the code):  python tools/build_scenarios_doc.py"""
import sys
from contextlib import closing
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
sys.path.insert(0, str(ROOT))
from src import vdb  # noqa: E402
from src.verification_engine import CHECK_ORDER, run_verification, safety_summary  # noqa: E402

SHORT = {"record_consistency": "Records", "registration_mutation": "Reg→Mut", "survey_chain": "Survey", "boundary_overlap": "Overlap",
         "conflicting_sales": "Sales", "document_integrity": "Hash", "document_authenticity": "Signed", "pending_cases": "Cases",
         "khas_acquisition": "Khas", "encumbrance": "Mortgage"}
MARK = {"PASS": "✓", "REVIEW_REQUIRED": "?", "CONFLICT_FOUND": "✗", "UNAVAILABLE": "–", "NOT_RUN": "·"}
DOT = {"green": "🟢", "amber": "🟡", "red": "🔴", "blue": "🔵", "grey": "⚪"}

vdb.ensure_db()
rows = []
with closing(vdb.connect()) as con:
    for p in vdb.list_parcels(con):
        pid = p["parcel_id"]
        run = run_verification(pid, vdb.get_records(con, pid), vdb.get_transactions(con, pid), vdb.get_documents(con, pid), context=vdb.verification_context(con, pid))
        assert [r["check_id"] for r in run["results"]] == CHECK_ORDER
        marks = "".join(MARK[r["status"]] for r in run["results"])
        ss = safety_summary(run)
        rows.append(f"| {pid} | {p['mouza']} | {p['asking_price_bdt'] / 1e5:,.1f} | {p['scenario_title']} | {p['scenario_description']} | `{marks}` | **{run['overall_status']}** | {DOT[ss['level']]} {ss['level']} |")
legend = " ".join(f"`{i + 1}`={SHORT[c]}" for i, c in enumerate(CHECK_ORDER))
text = f"""# Demo scenarios and expected results (Joydebpur, Gazipur: {len(rows)} synthetic parcels)

Generated by `tools/build_scenarios_doc.py` from the verification engine. All parcels, records, surveys, cases, notices, mortgages, signatures and documents are
**synthetic**. The strip shows the ten checks in order ({legend}): `✓` pass, `?` review required, `✗` conflict found, `–` unavailable.
Default settings: area tolerance 2%, overlap window 30 days, rapid-transfer window 60 days, mutation deadline 90 days, survey drift 15%, boundary-overlap
tolerance 1 m² or 1%. Every row is asserted by `tests/test_verification_engine.py::test_all_25_seeded_scenarios_produce_their_designed_result`.

| Parcel | Mouza | Asking price (lakh BDT, fictional) | Scenario | What it demonstrates | Checks | Overall | Light |
|---|---|---|---|---|---|---|---|
""" + "\n".join(rows) + """

Notes
- `PASS` and 🟢 appear only when every check ran and passed. Neither means a document is genuine or a title is clean.
- **DV-011** passes every record check on purpose. Its interesting result is on **Satellite & land use**: open Sentinel-2 imagery (dry seasons, 2018-12-13 vs
  2025-12-18) shows open farmland becoming dense development, while the synthetic records say agricultural land.
- **DV-018**: the deed was altered and its stored hash replaced, so the plain hash check passes, but the issuer signature and ledger fail.
- **DV-023 / DV-024**: each parcel's papers are consistent, but the two registered boundaries share about 94 m² (47% of each). Search `540`, press **Map**, click the darker strip.
- **DV-025**: everything is consistent except an active bank mortgage (amber).
- **DV-010** has no records and no register coverage. Only the boundary-overlap check can run, so the result is REVIEW_REQUIRED (amber), not a pass.
"""
(ROOT / "docs" / "DEMO_SCENARIOS.md").write_text(text)
print(f"wrote {len(rows)} rows")
